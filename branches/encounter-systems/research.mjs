import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { World, outputBytes, VERSION } from "./model.mjs";
import { referenceImage } from "./reference.mjs";
const root = import.meta.dirname;
const sha = (bytes) => createHash("sha256").update(bytes).digest("hex");
export function runResearch() {
  const scenarios = [];
  for (const task of ["fractal", "wave"])
    for (const buildDelay of [0, 1.1, 4])
      for (const partner of [false, true]) {
        const w = new World({ task, buildDelay });
        if (partner) w.command("partner");
        w.advanceTo(80);
        assert.equal(w.done, 48);
        assert.deepEqual(outputBytes(w), referenceImage(task));
        scenarios.push({
          id: `${task}-delay-${buildDelay}-${partner ? "partner" : "solo"}`,
          task,
          buildDelay,
          partner,
          done: w.done,
          ticks: w.tick,
          modelSeconds: Number(w.time.toFixed(6)),
          partnerTiles: w.partner.contributed,
          outputSha256: sha(outputBytes(w)),
        });
      }
  const revoke = new World();
  revoke.advanceTo(3);
  revoke.command("visit");
  revoke.advanceTo(4);
  const issuedEpoch = revoke.flights[0].epoch;
  revoke.setConsent(false);
  revoke.setConsent(true);
  revoke.advanceTo(6);
  assert.equal(revoke.visitor.copies.length, 0);
  const retained = new World();
  retained.advanceTo(3);
  retained.command("visit");
  retained.advanceTo(6);
  retained.setConsent(false);
  assert.equal(retained.visitor.copies.length, 3);
  const gate = new World();
  gate.advanceTo(3);
  const before = sha(gate.tiles[0].bytes);
  gate.command("write");
  gate.advanceTo(4);
  assert.equal(before, sha(gate.tiles[0].bytes));
  gate.setGuard(false);
  gate.command("write");
  gate.advanceTo(5);
  const changed = sha(gate.tiles[0].bytes);
  assert.notEqual(before, changed);
  gate.repair();
  assert.equal(before, sha(gate.tiles[0].bytes));
  return {
    schema: "halveth.encounter-results.v1",
    modelVersion: VERSION,
    sourceSha256: sha(
      fs
        .readFileSync(path.join(root, "model.mjs"), "utf8")
        .replace(/\r\n/g, "\n"),
    ),
    oracleSha256: sha(
      fs
        .readFileSync(path.join(root, "reference.mjs"), "utf8")
        .replace(/\r\n/g, "\n"),
    ),
    planSha256: sha(
      fs
        .readFileSync(path.join(root, "RESEARCH_PLAN.json"), "utf8")
        .replace(/\r\n/g, "\n"),
    ),
    measurement: "deterministic model ticks; no hardware speedup measured",
    scenarios,
    observations: {
      oldEpoch: issuedEpoch,
      newEpoch: revoke.epoch,
      oldDeliveryAccepted: false,
      retainedCopies: retained.visitor.copies.length,
      protectedBeforeSha256: before,
      unprotectedAfterSha256: changed,
      repairedSha256: sha(gate.tiles[0].bytes),
    },
  };
}
if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === path.join(root, "research.mjs")
) {
  const result = runResearch(),
    output = path.join(root, "results.json");
  const displayModule =
    "// Generated by research.mjs; SPDX-License-Identifier: MIT\n// Embedded research data: CC0-1.0\nexport const report = " +
    JSON.stringify(result, null, 2) +
    ";\n";
  if (process.argv.includes("--write")) {
    fs.writeFileSync(output, JSON.stringify(result, null, 2) + "\n");
    fs.writeFileSync(path.join(root, "results-data.mjs"), displayModule);
  } else if (process.argv.includes("--check")) {
    assert.deepEqual(result, JSON.parse(fs.readFileSync(output, "utf8")));
    assert.equal(
      fs
        .readFileSync(path.join(root, "results-data.mjs"), "utf8")
        .replace(/\r\n/g, "\n"),
      displayModule,
    );
  } else console.log(JSON.stringify(result, null, 2));
  console.log(
    `${result.scenarios.length} model comparisons; full-byte oracle and grant-epoch observations passed.`,
  );
}
